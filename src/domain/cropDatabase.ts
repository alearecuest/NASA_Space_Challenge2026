export const getCropLabel = (cropId: CropName): string => CROP_PROFILES[cropId].label

export const isCropSuitableForMonth = (
  cropId: CropName,
  month: number,
  action: 'sowing' | 'harvest',
): boolean => {
  const profile = CROP_PROFILES[cropId]
  const months = action === 'sowing' ? profile.sowingMonths : profile.harvestMonths
  return months.includes(month)
}
