import { useAIAnalysis } from '../hooks/useAIAnalysis'
import type { FieldData } from '../types/field'

const NO_ROTATIONS: never[] = []

interface AIInsightsProps {
  fieldData: FieldData | null
}

// AI output is rendered only as plain text (React escapes it): OWASP LLM05
export const AIInsights = ({ fieldData }: AIInsightsProps) => {
  const { analysis, isLoading, isOnline, lastSync } = useAIAnalysis(fieldData, NO_ROTATIONS)

  return (
    <section className="rounded-2xl border border-line bg-card p-5" aria-live="polite">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <div>
          <p className="text-xs font-bold uppercase tracking-[0.2em] text-lime">AI field insights</p>
          <h2 className="mt-1 text-xl font-extrabold text-ink">What the data says about your field</h2>
        </div>
        {analysis?.demo && (
          <span className="rounded-full border border-ocre px-3 py-1 text-xs font-bold uppercase tracking-wide text-ocre">Demo</span>
        )}
      </div>

      {!fieldData && <p className="mt-4 text-sky">Waiting for climate data from NASA POWER…</p>}
      {fieldData && isLoading && <p className="mt-4 text-sky">Analyzing your field…</p>}
      {fieldData && !isLoading && !isOnline && !analysis && (
        <p className="mt-4 text-sky">You are offline. The analysis will run when the connection returns.</p>
      )}

      {analysis && !isLoading && (
        <div className="mt-4 space-y-4">
          <p className="text-ink">{analysis.summary}</p>
          {analysis.risks.length > 0 && (
            <div>
              <h3 className="text-sm font-bold uppercase tracking-wide text-ocre">Risks</h3>
              <ul className="mt-2 space-y-1">
                {analysis.risks.map((r) => (
                  <li key={r} className="flex gap-2 text-sky"><span aria-hidden="true" className="text-ocre">●</span>{r}</li>
                ))}
              </ul>
            </div>
          )}
          {analysis.recommendations.length > 0 && (
            <div>
              <h3 className="text-sm font-bold uppercase tracking-wide text-lime">What to check</h3>
              <ul className="mt-2 space-y-1">
                {analysis.recommendations.map((r) => (
                  <li key={r} className="flex gap-2 text-sky"><span aria-hidden="true" className="text-lime">✓</span>{r}</li>
                ))}
              </ul>
            </div>
          )}
          <p className="border-t border-line pt-3 text-xs text-mute">
            {analysis.demo ? 'Example analysis (no AI key configured).' : `Generated by AI (${analysis.model ?? 'model'}) from NASA indicators.`}{' '}
            Advisory only: decide with your agronomist. Last saved {lastSync}.
          </p>
        </div>
      )}
    </section>
  )
}
